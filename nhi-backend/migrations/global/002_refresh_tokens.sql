-- Apply once to the shared nhi_db database (after 001).
-- Refresh tokens are opaque random strings; only their SHA-256 hash is stored.
BEGIN;

CREATE TABLE IF NOT EXISTS nhi_global.refresh_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES nhi_global.nhi_users (id) ON DELETE CASCADE,
    token_hash  text NOT NULL UNIQUE,
    expires_at  timestamptz NOT NULL,
    revoked_at  timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user
    ON nhi_global.refresh_tokens (user_id);

COMMIT;
