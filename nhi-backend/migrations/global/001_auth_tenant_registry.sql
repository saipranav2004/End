-- Apply once to the shared nhi_db database.
-- nhi_global is the authentication/registry schema; each tenant's data lives
-- in its own schema of the same database. tenant.db_name holds that tenant
-- schema's name (it is carried in the JWT as db_name).
-- For an existing deployment, backfill tenant_id/db_name and reconcile column
-- names before enforcing NOT NULL/foreign-key constraints.
BEGIN;

CREATE SCHEMA IF NOT EXISTS nhi_global;

CREATE TABLE IF NOT EXISTS nhi_global.tenants (
    tenant_id  uuid PRIMARY KEY,
    db_name    text NOT NULL UNIQUE
        CHECK (db_name ~ '^[A-Za-z_][A-Za-z0-9_]{0,62}$'), -- tenant schema name
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS nhi_global.nhi_users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text NOT NULL,
    password    text NOT NULL, -- bcrypt hash only
    full_name   text NOT NULL DEFAULT '',
    team        text NOT NULL DEFAULT '',
    role        text NOT NULL DEFAULT 'user',
    tenant_id   uuid NOT NULL REFERENCES nhi_global.tenants (tenant_id),
    status      text NOT NULL DEFAULT 'active',
    created_at  timestamptz NOT NULL DEFAULT now(),
    last_login_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_nhi_users_email_lower
    ON nhi_global.nhi_users (lower(trim(email)));
CREATE INDEX IF NOT EXISTS idx_nhi_users_tenant_status
    ON nhi_global.nhi_users (tenant_id, status);

COMMIT;
